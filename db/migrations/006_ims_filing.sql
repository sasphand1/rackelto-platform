CREATE TABLE IF NOT EXISTS ims_folders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, parent_id BIGINT UNSIGNED NULL,
 name VARCHAR(120) NOT NULL, restricted TINYINT(1) NOT NULL DEFAULT 1,
 owner_id BIGINT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(parent_id) REFERENCES ims_folders(id), FOREIGN KEY(owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_folder_permissions (
 folder_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 permission ENUM('read','write') NOT NULL, PRIMARY KEY(folder_id,user_id),
 FOREIGN KEY(folder_id) REFERENCES ims_folders(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_filing_files (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, folder_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL, owner_id BIGINT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(folder_id) REFERENCES ims_folders(id), FOREIGN KEY(owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_filing_versions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, file_id BIGINT UNSIGNED NOT NULL, revision INT UNSIGNED NOT NULL,
 filename VARCHAR(200) NOT NULL, media_type VARCHAR(100) NOT NULL, content MEDIUMBLOB NOT NULL,
 sha256 CHAR(64) NOT NULL, bytes INT UNSIGNED NOT NULL, created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(file_id,revision),
 FOREIGN KEY(file_id) REFERENCES ims_filing_files(id), FOREIGN KEY(created_by) REFERENCES users(id)
);
