CREATE TABLE IF NOT EXISTS ims_documents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(80) NOT NULL UNIQUE, title VARCHAR(200) NOT NULL,
 category VARCHAR(80) NOT NULL, owner_id BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_document_versions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 document_id BIGINT UNSIGNED NOT NULL, revision INT UNSIGNED NOT NULL,
 filename VARCHAR(200) NOT NULL, media_type VARCHAR(100) NOT NULL,
 content MEDIUMBLOB NOT NULL, sha256 CHAR(64) NOT NULL, bytes INT UNSIGNED NOT NULL,
 status ENUM('draft','review','approved','superseded','rejected') NOT NULL DEFAULT 'draft',
 created_by BIGINT UNSIGNED NOT NULL, reviewed_by BIGINT UNSIGNED NULL,
 review_note VARCHAR(1000), review_due DATE NULL, reviewed_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(document_id,revision), FOREIGN KEY(document_id) REFERENCES ims_documents(id),
 FOREIGN KEY(created_by) REFERENCES users(id), FOREIGN KEY(reviewed_by) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL,
 event_type VARCHAR(80) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL,
 detail JSON NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_id) REFERENCES users(id)
);
