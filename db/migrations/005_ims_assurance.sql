CREATE TABLE IF NOT EXISTS ims_assurance_reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, kind ENUM('internal_audit','management_review') NOT NULL,
 title VARCHAR(200) NOT NULL, outcome TEXT NOT NULL, owner_id BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_assurance_releases (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, commit_sha CHAR(40) NOT NULL, run_url VARCHAR(300) NOT NULL,
 outcome ENUM('passed','failed') NOT NULL, owner_id BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS ims_assurance_exports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL,
 sha256 CHAR(64) NOT NULL, content MEDIUMBLOB NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_id) REFERENCES users(id)
);
